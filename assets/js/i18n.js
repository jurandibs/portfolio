let currentLang = 'pt-BR';

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === 'en-US' ? 'en' : 'pt-BR';
  
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          // It's a placeholder if it's an input or textarea without innerHTML usage
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });

  // Special handling for Typed.js
  const typedSpan = document.querySelector('.typed');
  if (typedSpan) {
    typedSpan.setAttribute('data-typed-items', translations[lang]['hero_roles']);
  }

  // Update button active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.remove('active-lang');
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active-lang');
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      setLanguage(e.target.getAttribute('data-lang'));
      
      // Re-init typed.js if possible
      const selectTyped = document.querySelector('.typed');
      if (selectTyped) {
        let typed_strings = selectTyped.getAttribute('data-typed-items');
        typed_strings = typed_strings.split(',');
        
        // This relies on Typed being available globally
        if (window.typed_instance) {
           window.typed_instance.destroy();
        }
        
        if (typeof Typed !== 'undefined') {
            window.typed_instance = new Typed('.typed', {
                strings: typed_strings,
                loop: true,
                typeSpeed: 100,
                backSpeed: 50,
                backDelay: 2000
            });
        }
      }
    });
  });
});
